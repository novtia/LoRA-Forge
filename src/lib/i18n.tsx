interface I18nContextValue {
  language: SupportedLanguage;
  setLanguage: (language: SupportedLanguage) => void;
  t: TranslateFn;
  formatRelativeTime: (timestamp: number) => string;
  formatClock: (timestampSeconds: number) => string;
  statusLabel: (status: ProjectStatus | JobStatus) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detectLanguage(): SupportedLanguage {
  if (typeof window === "undefined") {
    return "en";
  }

  const stored = window.localStorage.getItem(I18N_STORAGE_KEY);
  if (stored === "en" || stored === "zh-CN") {
    return stored;
  }

  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function resolveIntlLocale(language: SupportedLanguage) {
  return language === "zh-CN" ? "zh-CN" : "en-US";
}

function interpolate(template: string, params?: TranslationParams) {
  if (!params) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const value = params[key];
    return value === undefined ? `{{${key}}}` : String(value);
  });
}

function statusKey(status: ProjectStatus | JobStatus) {
  switch (status) {
    case "running":
      return "status.running";
    case "paused":
      return "status.paused";
    case "completed":
      return "status.completed";
    case "error":
    case "failed":
      return "status.error";
    case "interrupted":
      return "status.interrupted";
    case "aborted":
      return "status.aborted";
    default:
      return "status.ready";
  }
}

function createTranslator(language: SupportedLanguage): TranslateFn {
  return (key, params) => {
    const template = MESSAGES[language][key] ?? MESSAGES.en[key] ?? key;
    return interpolate(template, params);
  };
}

function formatRelativeTimeForLanguage(language: SupportedLanguage, timestamp: number, t: TranslateFn) {
  const diffSeconds = Math.max(0, Math.floor(Date.now() / 1000) - timestamp);

  if (diffSeconds < 3600) {
    const count = Math.max(1, Math.floor(diffSeconds / 60) || 1);
    return t("relativeTime.minutesAgo", { count });
  }
  if (diffSeconds < 86400) {
    return t("relativeTime.hoursAgo", { count: Math.floor(diffSeconds / 3600) });
  }
  if (diffSeconds < 604800) {
    return t("relativeTime.daysAgo", { count: Math.floor(diffSeconds / 86400) });
  }
  return t("relativeTime.weeksAgo", { count: Math.floor(diffSeconds / 604800) });
}

function formatClockForLanguage(language: SupportedLanguage, timestampSeconds: number) {
  return new Intl.DateTimeFormat(resolveIntlLocale(language), {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  }).format(new Date(timestampSeconds * 1000));
}

export function getDesignPresetCopy(t: TranslateFn, presetId: DesignPresetId) {
  const baseKey = DESIGN_PRESET_KEY_MAP[presetId];
  return {
    name: t(`${baseKey}.name`),
    eyebrow: t(`${baseKey}.eyebrow`),
    description: t(`${baseKey}.description`),
  };
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<SupportedLanguage>(detectLanguage);

  useEffect(() => {
    window.localStorage.setItem(I18N_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const t = createTranslator(language);

    return {
      language,
      setLanguage,
      t,
      formatRelativeTime: (timestamp) => formatRelativeTimeForLanguage(language, timestamp, t),
      formatClock: (timestampSeconds) => formatClockForLanguage(language, timestampSeconds),
      statusLabel: (status) => t(statusKey(status)),
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return context;
}
